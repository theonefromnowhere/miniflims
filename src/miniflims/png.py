def _modulate_cos(terms, omega):
    """Separable expansion of  B_base * cos(omega (k1 + k2 + k3)).

    cos(A+B+C) = cA cB cC - cA sB sC - sA cB sC - sA sB cC: the cos counterpart
    of jaxpng.bispectra.modulate_sin (4 terms per base term).
    """
    pattern = [(1.0, "c", "c", "c"), (-1.0, "c", "s", "s"), (-1.0, "s", "c", "s"), (-1.0, "s", "s", "c")]

    def mk(g, kind, coeff):
        trig = jnp.sin if kind == "s" else jnp.cos
        return lambda k: coeff * g(k) * trig(omega * k)

    return [
        (mk(g1, a, c), mk(g2, b, 1.0), mk(g3, d, 1.0))
        for (g1, g2, g3) in terms
        for (c, a, b, d) in pattern
    ]


@dataclass(frozen=True)
class Template:
    shape_params: tuple  # names of shape parameters besides f_NL
    build: Callable  # (jaxpng, n_s, omega, phase) -> separable terms (phase: Python float)
    build_cos: Optional[Callable] = None  # (jaxpng, n_s, omega) -> terms of the phase = pi/2 version
    # squeezed limit B -> (k_L/k_S)^alpha P(k_L) P(k_S): sets the scale dependence
    # Delta b ~ k^alpha / M(k) of the png bias term (nonlocal_bias.py)
    squeezed_alpha: float = 0.0


def _feature_base(jp, n_s):
    P23 = lambda k: jp.grids.P_kernel(k, n_s) ** (2.0 / 3.0)  # noqa: E731
    return [(lambda k: 6.0 * P23(k), P23, P23)]


TEMPLATES = {
    "local": Template((), lambda jp, n_s, w, ph: jp.bispectra.local(n_s), squeezed_alpha=0.0),
    "equilateral": Template((), lambda jp, n_s, w, ph: jp.bispectra.equilateral(n_s), squeezed_alpha=2.0),
    "orthogonal": Template((), lambda jp, n_s, w, ph: jp.bispectra.orthogonal(n_s), squeezed_alpha=1.0),
    # 6 (P1 P2 P3)^(2/3) sin(omega (k1+k2+k3) + phase); squeezed limit
    # ~ (k_L/k_S) P_L P_S sin(2 omega k_S): alpha = 1, with an omega-dependent
    # amplitude that the free b_phi absorbs
    "feature": Template(
        ("omega", "phase"),
        lambda jp, n_s, w, ph: jp.bispectra.feature(n_s, w, ph),
        lambda jp, n_s, w: _modulate_cos(_feature_base(jp, n_s), w),
        squeezed_alpha=1.0,
    ),
    # equilateral template x sin(omega (k1+k2+k3) + phase): oscillation with a
    # suppressed squeezed limit
    "equilateral_feature": Template(
        ("omega", "phase"),
        lambda jp, n_s, w, ph: jp.bispectra.modulate_sin(jp.bispectra.equilateral(n_s), w, ph),
        lambda jp, n_s, w: _modulate_cos(jp.bispectra.equilateral(n_s), w),
        squeezed_alpha=2.0,
    ),
}

PARAM_DEFAULTS = {
    "f_NL": ParamSpec("f_NL", 0.0, -1.0e4, 1.0e4, 50.0),
    "omega": ParamSpec("omega", 20.0, 0.5, 500.0, 2.0, sample=False),  # Mpc/h
    "phase": ParamSpec("phase", 0.0, -math.pi, math.pi, 0.5, sample=False),
}


def poisson_kernel(k, cosmo: Cosmology, transfer: str = "eisenstein_hu"):
    """M(k) with delta(k, z=0) = M(k) Phi(k); 0 at k = 0."""
    T = TRANSFER_FUNCTIONS.get(transfer)(k, cosmo)
    d_md = 2.5 * cosmo.omega_m * _growth_unnorm(1.0, cosmo)  # D -> a in matter domination
    return (2.0 / 3.0) * k**2 * T * d_md / (cosmo.omega_m * H0**2)


# --------------------------------------------------------------------------- #
class PNGModel:
    """Non-Gaussian part of the linear density for one template."""

    def __init__(self, cfg, grid: Grid, cosmo: Cosmology, transfer: str, precision: str = "float64"):
        if cfg.template not in TEMPLATES:
            raise KeyError(f"unknown png.template '{cfg.template}'; available: {sorted(TEMPLATES)}")
        self.jp = import_jaxpng(cfg.jaxpng_path)
        jax.config.update("jax_enable_x64", precision == "float64")  # undo jaxpng's switch
        self.cfg = cfg
        self.template = TEMPLATES[cfg.template]
        self.box = self.jp.Box(N=grid.n, L=grid.box)
        self.n_s = float(cosmo.n_s)

        M = np.asarray(poisson_kernel(jnp.asarray(grid.kmag()), cosmo, transfer))
        self.M = jnp.asarray(M)
        self.inv_M = jnp.asarray(np.where(M > 0, 1.0 / np.where(M > 0, M, 1.0), 0.0))

        defaults = [PARAM_DEFAULTS["f_NL"]] + [PARAM_DEFAULTS[n] for n in self.template.shape_params]
        self.specs = resolve_specs(defaults, cfg.params, f"png ({cfg.template})")
        self.names = [s.name for s in self.specs]
        self.lower = jnp.asarray([s.lower for s in self.specs])
        self.upper = jnp.asarray([s.upper for s in self.specs])
        self.widths = jnp.asarray([s.width for s in self.specs])
        self.sampled = tuple(s.sample for s in self.specs)
        self.shape_sampled = any(s.sample for s in self.specs[1:])
        self._static = {s.name: float(s.init) for s in self.specs[1:] if not s.sample}
        if cfg.local_exact and cfg.template != "local":
            raise ValueError("png.local_exact only applies to template: local")
        if cfg.quadrature == "log":
            if cfg.n_t < 2:
                raise ValueError("png.n_t must be at least 2")
            if not hasattr(self.jp.phing, "schwinger_t_grid_log"):
                raise ImportError("png.quadrature: log needs jaxpng with phing.schwinger_t_grid_log "
                                  "(or set png.quadrature: jaxpng)")
            eps = 1e-5 if cfg.eps is None else cfg.eps
            self.t_grid = self.jp.phing.schwinger_t_grid_log(self.box, cfg.n_t, eps)
        elif cfg.quadrature == "jaxpng":
            self.t_grid = None
        else:
            raise ValueError(f"png.quadrature must be 'log' or 'jaxpng', not '{cfg.quadrature}'")

    # ------------------------------------------------------------ parameters
    def default(self) -> np.ndarray:
        return np.array([s.init for s in self.specs])

    def from_dict(self, values: dict) -> np.ndarray:
        unknown = set(values) - set(self.names)
        if unknown:
            raise ValueError(f"unknown PNG parameter(s) {sorted(unknown)}; valid: {self.names}")
        p = self.default()
        for name, v in values.items():
            p[self.names.index(name)] = float(v)
        return p

    def init(self, key, jitter: float = 0.0):
        p = jnp.asarray(self.default())
        if jitter > 0:
            span = self.upper - self.lower
            u = jax.random.uniform(key, p.shape, minval=-0.5, maxval=0.5)
            scat = jnp.clip(p + jitter * span * u, self.lower + 1e-6 * span, self.upper - 1e-6 * span)
            p = jnp.where(jnp.asarray(self.sampled), scat, p)
        return p

    def log_prior(self, p):
        lp = 0.0
        for i, s in enumerate(self.specs):
            if s.prior == "normal":
                lp = lp - 0.5 * ((p[i] - s.prior_mean) / s.prior_std) ** 2
        return lp

    def _shape(self, p, name, default=0.0):
        if name not in self.names:
            return default
        if name in self._static:
            return self._static[name]
        return p[self.names.index(name)]

    # --------------------------------------------------------------- physics
    def _phi_ng(self, phi_g_k, terms):
        c = self.cfg
        if self.t_grid is not None:
            return self.jp.phing.phiNG(phi_g_k, terms, self.box, self.n_s, remat=c.remat, t_grid=self.t_grid)
        eps = 1e-3 if c.eps is None else c.eps
        return self.jp.phing.phiNG(phi_g_k, terms, self.box, self.n_s, eps=eps,
                                   per_efold=c.per_efold, remat=c.remat)

    def phi_ng(self, phi_g_k, p):
        """Phi_NG(k) for the shape parameters in ``p`` (f_NL not applied)."""
        if self.cfg.local_exact:  # jaxpng's local anchor, exact: Phi_G^2 - <Phi_G^2>
            s = (self.box.N,) * 3
            phi = jnp.fft.irfftn(phi_g_k, s=s)
            return jnp.fft.rfftn(phi**2 - jnp.mean(phi**2)).at[0, 0, 0].set(0.0)
        omega = self._shape(p, "omega")
        if "phase" in self.names and "phase" not in self._static:
            phase = p[self.names.index("phase")]
            b_sin = self._phi_ng(phi_g_k, self.template.build(self.jp, self.n_s, omega, 0.0))
            b_cos = self._phi_ng(phi_g_k, self.template.build_cos(self.jp, self.n_s, omega))
            return jnp.cos(phase) * b_sin + jnp.sin(phase) * b_cos
        phase = self._static.get("phase", 0.0)
        return self._phi_ng(phi_g_k, self.template.build(self.jp, self.n_s, omega, phase))

    def ng_density_k(self, delta_g_k, p):
        """M(k) Phi_NG(k): the density added per unit f_NL (rfftn layout)."""
        return self.M * self.phi_ng(delta_g_k * self.inv_M, p)

    def density_k(self, delta_g_k, p):
        """Linear density delta_G + f_NL M Phi_NG (rfftn layout)."""
        return delta_g_k + p[0] * self.ng_density_k(delta_g_k, p)
