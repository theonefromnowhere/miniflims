"""Primordial non-Gaussianity of the initial conditions, through jaxpng.

The Gaussian linear field of miniflims, delta_G(k) = sqrt(P N^3/V) x(k), is
turned into the primordial potential with the Poisson kernel, the
non-Gaussian part is generated by jaxpng (the GENGARS Schwinger-parameterised
separable-bispectrum kernel), and the result is mapped back to density:

    Phi_G  = delta_G / M(k)
    Phi    = Phi_G + f_NL Phi_NG[Phi_G; template(omega, phase)]      (jaxpng)
    delta  = M(k) Phi = delta_G + f_NL M(k) Phi_NG

    M(k) = (2/3) k^2 T(k) D_md(z=0) / (Omega_m H0^2),   H0 = 100/c h/Mpc,

with D_md the growth factor normalised to a in matter domination. This is the
convention of jaxpng.cosmology.poisson_M (delta = M Phi, M > 0), evaluated
with miniflims' own transfer function. Phi_NG only needs the *shape*
P_Phi ∝ k^(n_s - 4), which jaxpng uses internally.

Parameters (sampled in the ``png`` Gibbs block, see blocks.py)
    f_NL          every template
    omega, phase  oscillatory templates; phase is traced through the identity
                  B(phase) = cos(phase) B_sin + sin(phase) B_cos, because
                  jaxpng builds its templates with a Python-float phase.

Memory: jaxpng's ``remat`` (on by default here) checkpoints the Schwinger
scan, so gradients through Phi_NG need O(N^3) memory instead of
O(N_t N_terms N^3).
"""
from __future__ import annotations

import importlib
import math
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Optional

import jax
import jax.numpy as jnp
import numpy as np

from .cosmology import Cosmology, _growth_unnorm
from .grid import Grid
from .params import ParamSpec, resolve_specs
from .transfer import TRANSFER_FUNCTIONS

C_LIGHT = 299792.458  # km/s
H0 = 100.0 / C_LIGHT  # h/Mpc


# --------------------------------------------------------------------------- #
# jaxpng import
# --------------------------------------------------------------------------- #
def import_jaxpng(path: Optional[str] = None):
    """Import jaxpng, from ``path`` (the project directory that contains the
    ``jaxpng`` package) if given, else from the environment.

    A ``jaxpng/`` project directory in the working directory has no
    ``__init__.py`` and would shadow the installed package as an empty
    namespace package; that case is detected and repaired. Importing jaxpng
    switches JAX to float64; callers restore their own precision.
    """
    if path is not None:
        path = str(Path(path).expanduser().resolve())
        if path not in sys.path:
            sys.path.insert(0, path)
    try:
        mod = importlib.import_module("jaxpng")
    except ImportError as e:
        raise ImportError(
            "png.enabled needs jaxpng: `pip install -e ./jaxpng --config-settings editable_mode=compat` "
            "or set png.jaxpng_path"
        ) from e
    if getattr(mod, "__file__", None) is None:  # namespace package: a project dir shadows it
        roots = [p for p in getattr(mod, "__path__", []) if (Path(p) / "jaxpng" / "__init__.py").exists()]
        if not roots:
            raise ImportError(f"'jaxpng' resolves to an empty namespace package at {list(mod.__path__)}")
        for name in [m for m in sys.modules if m == "jaxpng" or m.startswith("jaxpng.")]:
            del sys.modules[name]
        sys.path.insert(0, roots[0])
        mod = importlib.import_module("jaxpng")
    for sub in ("bispectra", "phing", "grids", "config"):
        importlib.import_module(f"jaxpng.{sub}")
    return mod


